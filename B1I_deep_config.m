function cfg = B1I_deep_config()
% Independent B1I/INS configuration. No GPS script is changed.
cfg=B1I_config();
cfg.deep.bootstrapSeconds=45; % Scalar acquisition/nav initialization only.
cfg.deep.dt=0.01;
cfg.deep.maxCoastSeconds=1;
cfg.deep.codeSigmaMeters=15;
cfg.deep.rateSigmaMps=1;
cfg.deep.rangeGateMeters=100;
cfg.deep.rateGateMps=15;
cfg.deep.feedbackGain=1; % Original vector-control target update; safety caps retained.
cfg.deep.accelerationAiding=true; % Propagate carrier frequency between navigation epochs.
cfg.deep.physicalRangeRate=true; % Consistent light-time model in feedback and filter.
cfg.deep.sourceCodeVariance=false; % Experimental source-style per-channel code weighting.
cfg.deep.sourceQualityModel=false; % Trial: GPS C/N0 masks and both noise laws scaled to B1I.
cfg.deep.sourceRangeWeight=false; % Independent ablations; do not tune together.
cfg.deep.sourceRateWeight=true; % Adopted after paired straight/vertical replay; range weights unchanged.
cfg.deep.sourceCn0Selection=false;
cfg.deep.bootstrapCovariance=false; % Experimental scalar prior; assess total accuracy, not height alone.
cfg.deep.navigationRefreshSeconds=6; % Decode completed, bounded prompt history.
cfg.deep.navigationWindowSeconds=90; % Covers complete D1 and D2 ephemerides.
cfg.deep.weakHoldSeconds=0.5; % Bounded aided hold, never a valid GNSS observation.
cfg.deep.adaptiveIntegration=true; % Source vector policy: 1/4 ms D1, 1/2 ms D2; verified NH only.
cfg.deep.reacquisitionSeconds=5; % Retry lost channels using only already received IQ.
cfg.deep.dynamicAcquisition=true;
cfg.deep.discoverySeconds=5;
cfg.deep.discoveryBatchSize=8;
cfg.deep.navigationProbationSeconds=120;
cfg.deep.maxCodeCorrectionChips=0.05;
cfg.deep.maxCarrierCorrectionHz=20;
cfg.deep.maxFeedbackPositionSigma=50;
cfg.deep.initialAttitudeDeg=[NaN,NaN,NaN]; % [yaw pitch roll], NED, degrees.
cfg.deep.initialVelocityNed=[NaN,NaN,NaN]; % Or estimate from Doppler.
cfg.deep.armBodyMeters=[NaN,NaN,NaN]; % IMU -> antenna, body FRD axes.
cfg.deep.gyroReferenceDegps=[0,0,0]; % Motion detector reference, NOT calibration.
cfg.deep.enableStaticConstraints=false; % Require independent evidence to enable.
cfg.imu.format='ros1bag'; % 'ros1bag', 'mat', 'csv'; MAT variable: imu Nx7.
cfg.imu.topic=''; % Explicit sensor_msgs/Imu topic; never select one silently.
cfg.imu.gyroUnits='rad/s';
cfg.imu.accelUnits='m/s^2';
cfg.imu.specificForceConfirmed=false; % Must include gravity, not gravity-removed.
cfg.imu.maxGapSeconds=0.03;
% t_IQ = (t_IMU - imuReferenceSeconds) * imuClockScale + offset.
% All are seconds. t_IQ=0 is the FIRST IQ sample, not acquisition start.
cfg.sync.imuReferenceSeconds=NaN;
cfg.sync.imuClockScale=1;
% Existing sync.confirmed=false, offset=NaN, axes=[] deliberately remain.
cfg.outputDir=fullfile(fileparts(mfilename('fullpath')),'~temp','b1i_deep');
end
